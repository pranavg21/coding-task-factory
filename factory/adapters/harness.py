"""Generates tests/run_tests.sh, the test harness every task package ships (required by the organisers).

Every harness, whatever the stack, prints one normalised line per test it ran:

    PASSED <test id>      FAILED <test id>      ERROR <test id>

so the proof runner judges every test the same way. A test that never ran prints nothing, and the
proof runner treats it as not passing.

    bash tests/run_tests.sh <repo_dir> pass_to_pass   # Condition 1: untouched base repo, existing tests
    bash tests/run_tests.sh <repo_dir> fail_to_pass   # Condition 3: base repo + new tests, must FAIL
    bash tests/run_tests.sh <repo_dir> all            # Condition 2: patched repo, everything passes

Test IDs per framework:
    pytest   tests/test_x.py::test_name                      (pytest node ID)
    vitest   packages/zod/src/x.test.ts::describe > test     (file relative to repo :: full name)
    jsontest jsoncpp_test::Fixture/name  or  feature::Fixture/name   (existing binary or the task's tests)
"""
from __future__ import annotations

import shlex

FRAMEWORKS = ("pytest", "vitest", "jsontest")


def _bash_array(name: str, items: list[str]) -> str:
    return f"{name}=(" + " ".join(shlex.quote(item) for item in items) + ")"


def _preamble(fail_to_pass: list[str], pass_to_pass: list[str]) -> list[str]:
    return [
        "#!/usr/bin/env bash",
        "# Generated by coding-task-factory. Do not edit by hand (record any edit in manual_interventions.json).",
        "# Usage: bash tests/run_tests.sh <repo_dir> <pass_to_pass|fail_to_pass|all>",
        "set -uo pipefail",
        'REPO_DIR="$(cd "${1:?usage: run_tests.sh <repo_dir> <pass_to_pass|fail_to_pass|all>}" && pwd)"',
        'SCOPE="${2:-all}"',
        'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        _bash_array("FAIL_TO_PASS", fail_to_pass),
        _bash_array("PASS_TO_PASS", pass_to_pass),
        'case "$SCOPE" in',
        '  fail_to_pass) IDS=("${FAIL_TO_PASS[@]}") ;;',
        '  pass_to_pass) IDS=("${PASS_TO_PASS[@]}") ;;',
        '  all) IDS=("${PASS_TO_PASS[@]}" "${FAIL_TO_PASS[@]}") ;;',
        '  *) echo "unknown scope: $SCOPE" >&2; exit 2 ;;',
        "esac",
        'if [ "${#IDS[@]}" -eq 0 ]; then echo "no tests in scope $SCOPE" >&2; exit 3; fi',
        "# Condition 1 runs against the untouched base repository, so nothing is copied for pass_to_pass.",
        'if [ "$SCOPE" != "pass_to_pass" ] && [ -d "$HERE/cases" ]; then cp -R "$HERE/cases/." "$REPO_DIR/"; fi',
        'cd "$REPO_DIR"',
    ]


def _pytest() -> list[str]:
    return [
        "# This checkout's own code must win over any installed copy of the package (e.g. an editable install).",
        'export PYTHONPATH="$REPO_DIR/src:$REPO_DIR${PYTHONPATH:+:$PYTHONPATH}"',
        "# -rA prints 'PASSED <id>' / 'FAILED <id>' / 'ERROR <id>' for every test.",
        'python -m pytest -q -p no:cacheprovider -rA --tb=short "${IDS[@]}"',
    ]


def _vitest(project: str) -> list[str]:
    proj = shlex.quote(project)
    return [
        'REPORT="$(mktemp)"',
        "# Condition 3 only needs the task's new test files; the other scopes run the whole project.",
        "FILES=()",
        'if [ "$SCOPE" = "fail_to_pass" ]; then',
        '  for id in "${IDS[@]}"; do f="${id%%::*}"; [[ " ${FILES[*]} " == *" $f "* ]] || FILES+=("$f"); done',
        "fi",
        f'node_modules/.bin/vitest run --project {proj} --reporter=json --outputFile="$REPORT" "${{FILES[@]}}" >/dev/null 2>&1',
        "STATUS=$?",
        "node -e '",
        '  const fs = require("fs"), path = require("path");',
        "  let report; try { report = JSON.parse(fs.readFileSync(process.argv[1], \"utf8\")); } catch { process.exit(0); }",
        "  const root = process.argv[2];",
        "  for (const file of report.testResults || []) {",
        "    const rel = path.relative(root, file.name).split(path.sep).join(\"/\");",
        "    for (const t of file.assertionResults || []) {",
        '      const s = t.status === "passed" ? "PASSED" : (t.status === "failed" ? "FAILED" : "SKIPPED");',
        '      console.log(s + " " + rel + "::" + t.fullName);',
        "    }",
        '    if ((file.assertionResults || []).length === 0 && file.status === "failed") console.log("ERROR " + rel);',
        "  }",
        "' \"$REPORT\" \"$REPO_DIR\"",
        'rm -f "$REPORT"',
        "exit $STATUS",
    ]


def _jsontest() -> list[str]:
    return [
        "# Build the library and the existing test binary in a fresh build directory.",
        'BUILD="$REPO_DIR/build-factory"',
        'cmake -S . -B "$BUILD" -G Ninja -DCMAKE_BUILD_TYPE=Release -DJSONCPP_WITH_POST_BUILD_UNITTEST=OFF '
        '-DJSONCPP_WITH_PKGCONFIG_SUPPORT=OFF -DBUILD_SHARED_LIBS=OFF >"$BUILD.log" 2>&1 '
        '&& ninja -C "$BUILD" >>"$BUILD.log" 2>&1',
        "BUILT=$?",
        "FEATURE_OK=1",
        "# The task's own tests are a separate program, so jsoncpp's build files are never edited.",
        'if [ "$BUILT" -eq 0 ] && [ "$SCOPE" != "pass_to_pass" ]; then',
        "  mapfile -t SRCS < <(cd \"$HERE/cases\" 2>/dev/null && find . -name '*.cpp' | sed 's|^\\./||')",
        '  if [ "${#SRCS[@]}" -gt 0 ]; then',
        '    g++ -std=c++17 -O1 -I include -I src/test_lib_json "${SRCS[@]}" src/test_lib_json/jsontest.cpp '
        '"$BUILD/lib/libjsoncpp.a" -o "$BUILD/feature_test" >>"$BUILD.log" 2>&1 || FEATURE_OK=0',
        "  fi",
        "fi",
        "FAILED=0",
        'for id in "${IDS[@]}"; do',
        '  binary="${id%%::*}"; name="${id#*::}"',
        '  case "$binary" in jsoncpp_test) exe="$BUILD/bin/jsoncpp_test" ;; feature) exe="$BUILD/feature_test" ;; *) exe="" ;; esac',
        '  if [ "$BUILT" -ne 0 ] || [ -z "$exe" ] || { [ "$binary" = feature ] && [ "$FEATURE_OK" -ne 1 ]; }; then',
        '    echo "ERROR $id"; FAILED=1; continue',
        "  fi",
        '  if "$exe" --test "$name" >/dev/null 2>&1; then echo "PASSED $id"; else echo "FAILED $id"; FAILED=1; fi',
        "done",
        'if [ "$BUILT" -ne 0 ] || [ "$FEATURE_OK" -ne 1 ]; then tail -n 40 "$BUILD.log" >&2; fi',
        "exit $FAILED",
    ]


def render_run_tests_sh(test_framework: str, fail_to_pass: list[str], pass_to_pass: list[str],
                        project: str = "") -> str:
    """The harness script text, with LF line endings."""
    if test_framework == "pytest":
        body = _pytest()
    elif test_framework == "vitest":
        body = _vitest(project or "zod")
    elif test_framework == "jsontest":
        body = _jsontest()
    else:
        raise NotImplementedError(f"No test harness for framework {test_framework!r} yet")
    return "\n".join([*_preamble(fail_to_pass, pass_to_pass), *body, ""])
